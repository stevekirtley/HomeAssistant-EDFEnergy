"""Token handling when EDF, or CloudFront in front of it, has a bad moment."""
from datetime import timedelta
from types import SimpleNamespace
from unittest import mock

import pytest

from homeassistant.util.dt import now

from custom_components.edfenergy_uk.api_client import (
  AuthenticationException,
  EDFEnergyApiClient,
  ServerException,
  calculate_token_retrieval_cooldown,
  is_cloudfront_error,
)

fetch_token_target = "custom_components.edfenergy_uk.api_client.EDFEnergyApiClient._EDFEnergyApiClient__async_fetch_token"

CLOUDFRONT_403 = """<!DOCTYPE HTML PUBLIC "-//W3C//DTD HTML 4.01 Transitional//EN">
<HTML><HEAD><TITLE>ERROR: The request could not be satisfied</TITLE></HEAD><BODY>
<H1>403 ERROR</H1><H2>The request could not be satisfied.</H2>
Generated by cloudfront (CloudFront)
</BODY></HTML>"""

KRAKEN_401 = '{"detail":"Authentication credentials were not provided."}'

class StubResponse:
  def __init__(self, status: int, text: str):
    self.status = status
    self._text = text
    self.request_info = SimpleNamespace(headers={})

  async def text(self):
    return self._text

def create_client(**kwargs):
  return EDFEnergyApiClient(api_key="test-key", **kwargs)

def set_token_as_retrieved(client: EDFEnergyApiClient):
  client._graphql_token = "test-token"
  client._graphql_expiration = now() + timedelta(hours=1)

@pytest.mark.parametrize("status,text,expected", [
  (403, CLOUDFRONT_403, True),
  (403, KRAKEN_401, False),
  (401, CLOUDFRONT_403, False),
  (403, None, False),
])
def test_is_cloudfront_error(status, text, expected):
  assert is_cloudfront_error(status, text) == expected

@pytest.mark.asyncio
async def test_when_cloudfront_returns_403_then_server_exception_and_token_kept():
  # Arrange
  client = create_client()
  set_token_as_retrieved(client)

  # Act
  with pytest.raises(ServerException):
    await client.__async_read_response__(StubResponse(403, CLOUDFRONT_403), "https://example")

  # Assert
  assert client._graphql_token == "test-token"

@pytest.mark.asyncio
@pytest.mark.parametrize("status", [401, 403])
async def test_when_kraken_rejects_request_then_access_token_dropped_and_refresh_token_kept(status):
  # Arrange
  client = EDFEnergyApiClient(refresh_token="stored-refresh-token")
  set_token_as_retrieved(client)

  # Act
  with pytest.raises(AuthenticationException):
    await client.__async_read_response__(StubResponse(status, KRAKEN_401), "https://example")

  # Assert
  assert client._graphql_token is None
  assert client._graphql_expiration is None
  assert client._graphql_refresh_token == "stored-refresh-token"

@pytest.mark.parametrize("failures,expected_minutes", [
  (0, 0),
  (1, 1),
  (2, 2),
  (3, 4),
  (5, 16),
  (6, 30),
  (20, 30),
])
def test_calculate_token_retrieval_cooldown(failures, expected_minutes):
  assert calculate_token_retrieval_cooldown(failures) == timedelta(minutes=expected_minutes)

@pytest.mark.asyncio
async def test_when_token_retrieval_fails_with_server_exception_then_cooldown_is_set():
  # Arrange
  client = create_client()

  # Act
  with mock.patch(fetch_token_target, side_effect=ServerException("blip")):
    with pytest.raises(ServerException):
      await client.async_refresh_token()

  # Assert
  assert client._token_retrieval_failures == 1
  assert client._token_retrieval_cooldown_until > now()

@pytest.mark.asyncio
async def test_when_cooldown_is_active_then_token_retrieval_is_not_attempted():
  # Arrange
  client = create_client()
  with mock.patch(fetch_token_target, side_effect=ServerException("blip")):
    with pytest.raises(ServerException):
      await client.async_refresh_token()

  # Act
  with mock.patch(fetch_token_target, side_effect=ServerException("blip")) as fetch_token:
    with pytest.raises(ServerException):
      await client.async_refresh_token()

  # Assert
  assert fetch_token.call_count == 0
  assert client._token_retrieval_failures == 1

@pytest.mark.asyncio
async def test_when_cooldown_has_elapsed_then_token_retrieval_is_attempted_and_backs_off_further():
  # Arrange
  client = create_client()
  with mock.patch(fetch_token_target, side_effect=ServerException("blip")):
    with pytest.raises(ServerException):
      await client.async_refresh_token()
  client._token_retrieval_cooldown_until = now() - timedelta(minutes=1)

  # Act
  with mock.patch(fetch_token_target, side_effect=ServerException("blip")) as fetch_token:
    with pytest.raises(ServerException):
      await client.async_refresh_token()

  # Assert
  assert fetch_token.call_count == 1
  assert client._token_retrieval_failures == 2
  assert client._token_retrieval_cooldown_until > now() + timedelta(seconds=90)

@pytest.mark.asyncio
async def test_when_token_retrieval_succeeds_then_cooldown_is_cleared():
  # Arrange
  client = create_client()
  with mock.patch(fetch_token_target, side_effect=ServerException("blip")):
    with pytest.raises(ServerException):
      await client.async_refresh_token()
  client._token_retrieval_cooldown_until = now() - timedelta(minutes=1)

  # Act
  with mock.patch(fetch_token_target, side_effect=lambda: set_token_as_retrieved(client)):
    await client.async_refresh_token()

  # Assert
  assert client._token_retrieval_failures == 0
  assert client._token_retrieval_cooldown_until is None

@pytest.mark.asyncio
async def test_when_credentials_are_rejected_then_cooldown_is_not_involved():
  # Arrange
  client = create_client()

  # Act
  with mock.patch(fetch_token_target, side_effect=AuthenticationException("invalid", [])):
    with pytest.raises(AuthenticationException):
      await client.async_refresh_token()

  # Assert
  assert client._token_retrieval_failures == 0
  assert client._token_retrieval_cooldown_until is None
